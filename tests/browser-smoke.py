"""Run against `npm run demo`; tests only the loopback, in-memory UI."""
import json, os, shutil, uuid
from urllib.parse import quote
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[1]
checks=[]
def record(name): checks.append({'check':name,'result':'passed'})
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=os.environ.get('BROWSER_EXECUTABLE') or shutil.which('chromium'),args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1100},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    page.goto('http://127.0.0.1:4317/',wait_until='networkidle')
    page.get_by_role('button',name='Explorar demonstração').click()
    expect(page.locator('#stat-total')).to_have_text('2')
    expect(page.locator('#ticket-title')).to_have_text('Relatório de ensaio não foi concluído')
    expect(page.locator('#note-tab')).to_be_visible()
    record('Agent sees two authorized accounts and internal note control')
    # All data remains local. These assertions need an authorized browser; no bypass flags are added.
    expect(page.locator('#priority-form')).to_be_visible()
    page.locator('#message-body').fill('Rascunho público preservado pela prioridade.')
    page.locator('#ticket-priority').select_option('urgent')
    page.locator('#priority-reason').fill('Justificativa restrita ao atendimento.')
    page.locator('#save-priority').click()
    expect(page.locator('#ticket-tags')).to_contain_text('Urgente')
    expect(page.locator('#message-body')).to_have_value('Rascunho público preservado pela prioridade.')
    page.locator('#history-section summary').click()
    expect(page.locator('#history-list')).to_contain_text('Prioridade alterada')
    expect(page.locator('#history-list')).to_contain_text('Justificativa restrita ao atendimento.')
    record('Operator changes priority with private reason and keeps the public message draft')
    # A second real API call advances the version while the first tab still holds the old one.
    cfg=page.request.get('http://127.0.0.1:4317/demo-config').json()
    actor=next(x for x in cfg['profiles'] if x['key']=='agent')
    headers={'authorization':'Bearer '+actor['token'],'x-workspace-id':actor['workspace_id'],'content-type':'application/json'}
    found=page.request.get('http://127.0.0.1:4317/v1/tickets?q='+quote('Relatório de ensaio'),headers=headers).json()['items'][0]
    external=page.request.patch('http://127.0.0.1:4317/v1/tickets/'+found['id'],headers={**headers,'if-match':'"'+str(found['version'])+'"','idempotency-key':str(uuid.uuid4())},data={'priority':'normal','reason':'Alteração de outra sessão.'})
    assert external.status==200
    page.locator('#ticket-priority').select_option('high')
    page.locator('#priority-reason').fill('Motivo preservado após conflito.')
    page.locator('#save-priority').click()
    expect(page.locator('#priority-status')).to_contain_text('Outro atendimento modificou')
    expect(page.locator('#priority-reload')).to_be_visible()
    expect(page.locator('#priority-reason')).to_have_value('Motivo preservado após conflito.')
    page.locator('#priority-reload').click()
    expect(page.locator('#priority-status')).to_contain_text('Versão atualizada')
    page.locator('#save-priority').click()
    expect(page.locator('#ticket-tags')).to_contain_text('Alta')
    expect(page.locator('#priority-reason')).to_have_value('')
    record('Real 412 conflict requires explicit refresh and preserves the internal reason')
    held_priority=[]
    def hold_priority(route):
        if route.request.method=='PATCH': held_priority.append(route)
        else: route.continue_()
    page.route('**/v1/tickets/*',hold_priority)
    page.locator('#ticket-priority').select_option('urgent')
    page.locator('#priority-reason').fill('Motivo enviado primeiro.')
    with page.expect_request(lambda r: r.method=='PATCH'):
        page.locator('#save-priority').click()
    page.wait_for_timeout(50)
    assert held_priority
    page.locator('#ticket-priority').select_option('low')
    page.locator('#priority-reason').fill('Novo rascunho de prioridade.')
    held_priority.pop(0).continue_()
    expect(page.locator('#ticket-tags')).to_contain_text('Urgente')
    expect(page.locator('#priority-reason')).to_have_value('Novo rascunho de prioridade.')
    expect(page.locator('#ticket-priority')).to_have_value('low')
    page.unroute('**/v1/tickets/*',hold_priority)
    record('Late priority acknowledgement does not erase edits made during the save')
    page.locator('#profile').select_option('laboratory')
    expect(page.locator('#stat-total')).to_have_text('1')
    expect(page.locator('#priority-form')).not_to_be_visible()
    page.locator('#history-section summary').click()
    expect(page.locator('#history-list')).to_contain_text('Prioridade alterada')
    expect(page.locator('#history-list')).not_to_contain_text('Motivo enviado primeiro.')
    expect(page.locator('#history-list')).not_to_contain_text('Nota interna registrada')
    record('Client history displays priority but neither internal justification nor notes')
    page.locator('#profile').select_option('agent')
    expect(page.locator('#stat-total')).to_have_text('2')
    held_history=[]
    def hold_history(route): held_history.append(route)
    page.route('**/v1/tickets/*/timeline?*',hold_history)
    with page.expect_request(lambda r: '/timeline?' in r.url):
        page.locator('#history-section summary').click()
    page.wait_for_timeout(50)
    assert held_history
    page.unroute('**/v1/tickets/*/timeline?*',hold_history)
    page.get_by_role('button',name='Abrir chamado: Dúvida na emissão de boletins',exact=True).click()
    expect(page.locator('#ticket-title')).to_have_text('Dúvida na emissão de boletins')
    page.locator('#history-section summary').click()
    expect(page.locator('#history-list')).to_contain_text('Chamado aberto')
    held_history.pop(0).continue_()
    page.wait_for_load_state('networkidle')
    expect(page.locator('#history-list')).not_to_contain_text('Prioridade alterada')
    page.get_by_role('button',name='Abrir chamado: Relatório de ensaio não foi concluído',exact=True).click()
    expect(page.locator('#ticket-title')).to_have_text('Relatório de ensaio não foi concluído')
    record('Late history cannot replace events belonging to another selected ticket')
    # Server-side filters must not change the selected detail or discard a draft.
    page.locator('#message-body').fill('Rascunho preservado enquanto a lista é filtrada.')
    page.locator('#search').fill('boletins')
    page.locator('#status-filter').select_option('received')
    page.locator('#priority-filter').select_option('normal')
    page.locator('#apply-filters').click()
    expect(page.locator('#stat-total')).to_have_text('1')
    expect(page.locator('#ticket-list')).to_contain_text('Dúvida na emissão de boletins')
    expect(page.locator('#ticket-list')).not_to_contain_text('Relatório de ensaio')
    expect(page.locator('#ticket-title')).to_have_text('Relatório de ensaio não foi concluído')
    expect(page.locator('#message-body')).to_have_value('Rascunho preservado enquanto a lista é filtrada.')
    page.locator('#priority-filter').select_option('urgent')
    page.locator('#apply-filters').click()
    expect(page.locator('#stat-total')).to_have_text('0')
    expect(page.locator('#ticket-list')).to_contain_text('Nenhum chamado encontrado')
    record('Server-side query, public status and priority combine without erasing selected detail draft')
    page.locator('#clear-filters').click()
    expect(page.locator('#stat-total')).to_have_text('2')
    expect(page.locator('#search')).to_have_value('')
    expect(page.locator('#status-filter')).to_have_value('')
    expect(page.locator('#priority-filter')).to_have_value('')
    expect(page.locator('#message-body')).to_have_value('Rascunho preservado enquanto a lista é filtrada.')
    record('Clearing filters restores the authorized list and preserves the draft')
    # Hold one old query and release only after a different real query has completed.
    held_list=[]
    def hold_old_list(route):
        if 'q=boletins' in route.request.url: held_list.append(route)
        else: route.continue_()
    page.route('**/v1/tickets?*',hold_old_list)
    page.locator('#search').fill('boletins')
    with page.expect_request(lambda r: '/v1/tickets?' in r.url and 'q=boletins' in r.url):
        page.locator('#apply-filters').click()
    page.wait_for_timeout(50)
    assert held_list, 'Old list query was not observed'
    page.locator('#search').fill('Relatório')
    page.locator('#apply-filters').click()
    expect(page.locator('#stat-total')).to_have_text('1')
    expect(page.locator('#ticket-list')).to_contain_text('Relatório de ensaio')
    held_list.pop(0).continue_()
    page.wait_for_load_state('networkidle')
    expect(page.locator('#stat-total')).to_have_text('1')
    expect(page.locator('#ticket-list')).not_to_contain_text('boletins')
    expect(page.locator('#message-body')).to_have_value('Rascunho preservado enquanto a lista é filtrada.')
    page.unroute('**/v1/tickets?*',hold_old_list)
    page.locator('#clear-filters').click()
    expect(page.locator('#stat-total')).to_have_text('2')
    page.locator('#message-body').fill('')
    record('Late search response cannot replace a newer query or its selected conversation')
    page.screenshot(path=str(ROOT/'evidence/interface-desktop.png'),full_page=True)
    page.get_by_role('button',name='＋ Novo chamado',exact=True).click()
    expect(page.locator('#context-choice option')).to_have_count(3)
    expect(page.locator('#context-choice')).to_have_value('')
    expect(page.locator('#submit-create')).to_be_disabled()
    expect(page.locator('#context-choice')).to_contain_text('Laboratório Horizonte')
    expect(page.locator('#context-choice')).to_contain_text('Escola Caminhos')
    assert page.locator('#account-id, #instance-id, #manual-context').count() == 0
    record('Guided opening displays authorized names and requires a choice for multiple accounts')
    page.locator('#cancel-create').click()
    expect(page.locator('#create-dialog')).not_to_be_visible()
    page.locator('#profile').select_option('laboratory')
    expect(page.locator('#stat-total')).to_have_text('1')
    expect(page.locator('#note-tab')).to_be_hidden()
    expect(page.locator('#notes-section')).to_be_hidden()
    expect(page.locator('#notes')).to_have_text('')
    expect(page.locator('#ticket-list')).not_to_contain_text('boletins')
    record('Laboratory requester sees only own account; internal content cleared on role switch')
    page.get_by_role('button',name='＋ Novo chamado',exact=True).click()
    expect(page.locator('#context-choice option')).to_have_count(2)
    expect(page.locator('#context-choice')).not_to_have_value('')
    expect(page.locator('#context-choice')).not_to_contain_text('Escola Caminhos')
    expect(page.locator('#submit-create')).to_be_enabled()
    record('Sole authorized context is automatically selected without UUID entry')
    page.locator('#subject').fill('Teste de abertura pelo portal')
    page.locator('#description').fill('Solicitação fictícia criada por teste automatizado de navegador.')
    page.get_by_role('button',name='Validar e abrir chamado').click()
    expect(page.locator('#create-dialog')).not_to_be_visible()
    expect(page.locator('#ticket-title')).to_have_text('Teste de abertura pelo portal')
    expect(page.locator('#stat-total')).to_have_text('2')
    record('Requester resolves contract and opens a ticket through the interface')
    page.locator('#message-body').fill('Mensagem pública de teste.')
    page.get_by_role('button',name='Enviar resposta',exact=True).click()
    expect(page.locator('#messages')).to_contain_text('Mensagem pública de teste.')
    record('Public conversation supports sending and reading a real API message')
    page.locator('#profile').select_option('agent')
    expect(page.locator('#stat-total')).to_have_text('3')
    page.get_by_role('button',name='Abrir chamado: Teste de abertura pelo portal',exact=True).click()
    expect(page.locator('#ticket-title')).to_have_text('Teste de abertura pelo portal')
    page.locator('#note-tab').click()
    page.locator('#message-body').fill('Nota restrita do teste de navegador.')
    page.get_by_role('button',name='Salvar nota',exact=True).click()
    expect(page.locator('#notes')).to_contain_text('Nota restrita do teste de navegador.')
    record('Agent saves internal note separately from public conversation')
    # Hold a real request before it reaches the in-memory API. No sleep-based server stub.
    pending=[]
    def hold_message(route):
        if route.request.method == 'POST': pending.append(route)
        else: route.continue_()
    page.route('**/v1/tickets/*/messages', hold_message)
    page.locator('[data-mode="public"]').click()
    page.locator('#message-body').fill('Mensagem enviada antes do próximo rascunho.')
    with page.expect_request(lambda r: r.method == 'POST' and r.url.endswith('/messages')):
        page.get_by_role('button',name='Enviar resposta',exact=True).click()
    page.wait_for_timeout(50)
    assert pending, 'Held message request not observed'
    page.locator('#message-body').fill('Este rascunho novo não pode desaparecer.')
    pending.pop(0).continue_()
    expect(page.locator('#messages')).to_contain_text('Mensagem enviada antes do próximo rascunho.')
    expect(page.locator('#message-body')).to_have_value('Este rascunho novo não pode desaparecer.')
    record('Late completion preserves a newer draft in the same conversation')
    page.locator('#message-body').fill('Mensagem do chamado anterior.')
    with page.expect_request(lambda r: r.method == 'POST' and r.url.endswith('/messages')):
        page.get_by_role('button',name='Enviar resposta',exact=True).click()
    page.wait_for_timeout(50)
    assert pending, 'Second held request not observed'
    page.get_by_role('button',name='Abrir chamado: Dúvida na emissão de boletins',exact=True).click()
    expect(page.locator('#ticket-title')).to_have_text('Dúvida na emissão de boletins')
    page.locator('#message-body').fill('Rascunho exclusivo da escola.')
    pending.pop(0).continue_()
    page.wait_for_load_state('networkidle')
    expect(page.locator('#ticket-title')).to_have_text('Dúvida na emissão de boletins')
    expect(page.locator('#message-body')).to_have_value('Rascunho exclusivo da escola.')
    expect(page.locator('#messages')).not_to_contain_text('Mensagem do chamado anterior.')
    page.unroute('**/v1/tickets/*/messages', hold_message)
    record('Late completion cannot navigate back or erase another ticket draft')
    page.locator('#profile').select_option('school')
    expect(page.locator('#stat-total')).to_have_text('1')
    expect(page.locator('#ticket-list')).to_contain_text('boletins')
    expect(page.locator('#notes')).to_have_text('')
    record('Second product remains isolated after switching from agent')
    # A late response from a closed dialog must not replace a newer profile's catalogue.
    held_catalog=[]
    def hold_catalog(route): held_catalog.append(route)
    page.route('**/v1/support-contexts?*',hold_catalog)
    with page.expect_request(lambda r: '/v1/support-contexts?' in r.url):
        page.get_by_role('button',name='＋ Novo chamado',exact=True).click()
    page.wait_for_timeout(50)
    assert held_catalog
    page.locator('#cancel-create').click()
    page.unroute('**/v1/support-contexts?*',hold_catalog)
    page.locator('#profile').select_option('laboratory')
    expect(page.locator('#stat-total')).to_have_text('2')
    page.get_by_role('button',name='＋ Novo chamado',exact=True).click()
    expect(page.locator('#context-choice')).to_contain_text('Laboratório Horizonte')
    held_catalog.pop(0).continue_()
    page.wait_for_load_state('networkidle')
    expect(page.locator('#context-choice')).not_to_contain_text('Escola Caminhos')
    expect(page.locator('#context-choice')).not_to_have_value('')
    record('Late catalog response from another profile cannot replace the current selection')
    page.locator('#cancel-create').click()
    page.set_viewport_size({'width':390,'height':844})
    page.wait_for_timeout(200)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Horizontal overflow'
    page.screenshot(path=str(ROOT/'evidence/interface-mobile.png'),full_page=True)
    record('390px mobile layout has no horizontal overflow')
    page.get_by_role('button',name='◇ Arquitetura e estágio').click()
    expect(page.locator('#guide-view')).to_be_visible()
    record('Roadmap screen identifies implementation versus pending production features')
    assert not errors, errors
    record('No browser JavaScript exceptions')
    browser.close()
(ROOT/'evidence/browser-smoke.json').write_text(json.dumps({'checks':checks,'browser_errors':errors},ensure_ascii=False,indent=2))
print(json.dumps(checks,ensure_ascii=False,indent=2))
